"""Personal-baseline check on REAL NASA data: OSD-575 (Inspiration4, LSDS-8 CMP).

For every crew member and serum analyte, the pre-flight samples (L-92, L-44, L-3)
form a personal baseline (mean, SD; SD floored at 3 % of the mean because three
samples underestimate variability). Each post-flight sample (R+1, R+45, R+82,
R+194) is flagged when |z| >= 2 against that baseline. The same values are also
checked against the laboratory reference range printed in the file.

Standard library only. Usage:
  python analysis/validate_osd575.py OSD_575_data/LSDS-8_Comprehensive_Metabolic_Panel_CMP.upload_SUBMITTED.csv
AI disclosure: written with the help of Claude (Anthropic).
"""
import csv, collections, statistics as st, json, sys, os, datetime

SKIP = {"ALBUMIN/GLOBULIN RATIO", "BUN/CREATININE RATIO", "eGFR AFRICAN AMERICAN", "eGFR NON-AFR. AMERICAN", "GLOBULIN"}
PRE = ["L-92", "L-44", "L-3"]; POST = ["R+1", "R+45", "R+82", "R+194"]
Z_FLAG, SD_FLOOR = 2.0, 0.03
NICE = {"ALT": "ALT", "AST": "AST", "UREA NITROGEN (BUN)": "Urea nitrogen (BUN)", "BILIRUBIN; TOTAL": "Bilirubin, total", "PROTEIN; TOTAL": "Protein, total", "CARBON DIOXIDE": "CO2 (bicarbonate)"}

def main(src, out_js):
    rows = list(csv.DictReader(open(src, encoding="utf-8-sig")))
    d = collections.defaultdict(dict); rng = {}; units = {}
    for i, r in enumerate(rows, start=2):
        a = r["ANALYTE"]
        if a in SKIP: continue
        try: v = float(r["VALUE"])
        except ValueError: continue
        d[(a, r["SUBJECT_ID"])][r["timepoint"]] = (v, i)
        try: rng[(a, r["SUBJECT_ID"], r["timepoint"])] = (float(r["RANGE_MIN"]), float(r["RANGE_MAX"]))
        except ValueError: pass
        units[a] = r["UNITS"]
    res = []
    for (a, s), tp in sorted(d.items()):
        pre = [tp[t][0] for t in PRE if t in tp]
        if len(pre) < 2: continue
        m = st.mean(pre); sd = st.stdev(pre); sdf = max(sd, SD_FLOOR * abs(m))
        for t in POST:
            if t not in tp: continue
            v, row = tp[t]; z = (v - m) / sdf
            lr = rng.get((a, s, t)); inlab = (lr[0] <= v <= lr[1]) if lr else None
            res.append(dict(analyte=NICE.get(a, a.title().replace("; ", " ")), subject=s, timepoint=t, value=v, unit=units[a],
                            pre_mean=round(m, 2), z=round(z, 2), pct=round((v - m) / m * 100, 1) if m else None,
                            personal_flag=abs(z) >= Z_FLAG, lab_low=lr[0] if lr else None, lab_high=lr[1] if lr else None,
                            in_lab_range=inlab, source_row=row))
    by_tp = {t: dict(comparisons=sum(o["timepoint"] == t for o in res),
                     personal=sum(o["timepoint"] == t and o["personal_flag"] for o in res),
                     lab=sum(o["timepoint"] == t and o["in_lab_range"] is False for o in res),
                     personal_only=sum(o["timepoint"] == t and o["personal_flag"] and o["in_lab_range"] for o in res)) for t in POST}
    r1 = sorted([o for o in res if o["timepoint"] == "R+1" and o["personal_flag"]], key=lambda o: -abs(o["z"]))
    payload = dict(dataset="NASA OSDR OSD-575 (Inspiration4, LSDS-8 Comprehensive Metabolic Panel)",
                   url="https://osdr.nasa.gov/bio/repo/data/studies/OSD-575", file=os.path.basename(src),
                   crew_n=len({k[1] for k in d}), analytes_n=len({k[0] for k in d}),
                   method=f"Personal baseline = mean of {', '.join(PRE)}; SD floored at {int(SD_FLOOR*100)} % of mean; flag when |z| >= {Z_FLAG}.",
                   by_timepoint=by_tp, r1_flags=r1, generated=datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    with open(out_js, "w") as f:
        f.write(f"/* Generated by analysis/validate_osd575.py on {payload['generated']} from real NASA OSDR OSD-575 data. AI disclosure: script written with the help of Claude (Anthropic). */\n")
        f.write("window.SV_VAL = " + json.dumps(payload) + ";\n")
    print(json.dumps(by_tp, indent=1))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "data", "osd575_validation.js"))
